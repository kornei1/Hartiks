"""Централізований словник одиниць виміру HART протоколу"""

# Словник кодів одиниць виміру HART
# Формат: код (десяткова): "назва одиниці"
UNITS = {
    19: "m3/h",      # Кубічні метри на годину (витрата)
    21: "m/s",       # Метри в секунду (швидкість)
    32: "degC",      # Градуси Цельсія (температура)
    38: "Hz",        # Герци (частота)
    39: "mA",        # Мілі-ампери (струм)
    40: "kOhm",      # КілоОми (опір)
    41: "Ohm",       # Оми (опір)
    43: "m3",        # Кубічні метри (об'єм)
    44: "m",         # Метри (довжина)
    57: "%",         # Відсотки
    59: "pH",        # pH (кислотність)
    123: "dB",       # Децибели (0x7B в шістнадцятковій системі)
}

def get_unit_name(unit_code: int, default: str = None) -> str:
    """
    Отримати назву одиниці по коду.
    
    Args:
        unit_code: Числовий код одиниці з HART протоколу
        default: Значення за замовчуванням, якщо код не знайдено
                 (якщо None, повернеться строкове представлення коду)
    
    Returns:
        Назва одиниці або код у форматі, якщо не знайдено
    """
    if unit_code == 250:  # Unused
        return ""
    if unit_code == 0:    # Dimensionless
        return ""
    
    if default is None:
        return UNITS.get(unit_code, str(unit_code))
    else:
        return UNITS.get(unit_code, default)
